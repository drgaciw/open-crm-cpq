package com.opencrm.pricing.grpc;

import com.opencrm.common.grpc.PriceRequest;
import com.opencrm.common.grpc.PriceResponse;
import com.opencrm.common.grpc.PricingServiceGrpc;
import com.opencrm.common.valueobject.Money;
import com.opencrm.pricing.engine.PriceCalculationService;
import io.grpc.ManagedChannel;
import io.grpc.Server;
import io.grpc.health.v1.HealthCheckRequest;
import io.grpc.health.v1.HealthCheckResponse;
import io.grpc.health.v1.HealthGrpc;
import io.grpc.inprocess.InProcessChannelBuilder;
import io.grpc.inprocess.InProcessServerBuilder;
import io.grpc.protobuf.services.HealthStatusManager;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.Map;
import java.util.concurrent.TimeUnit;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyMap;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * Sends real gRPC calls through an in-process transport, so messages are serialized and parsed by
 * grpc-protobuf's marshaller instead of being handed to the service as Java objects.
 *
 * <p>This covers the protobuf runtime against two kinds of generated code: our own
 * {@code pricing.proto} classes, generated by {@code protoc ${protobuf.version}}, and the
 * {@code grpc.health.v1} classes that ship pre-generated inside {@code grpc-services}. The
 * grpc-server starter puts {@code grpc-services} on the classpath. The unit test
 * {@link PricingGrpcServiceTest} never touches the wire or {@code grpc-services}.
 */
@DisplayName("Pricing gRPC - in-process round trip (protobuf runtime vs generated code)")
class PricingGrpcInProcessRoundTripTest {

    private Server server;
    private ManagedChannel channel;
    private PriceCalculationService priceCalculationService;

    @BeforeEach
    void startInProcessServer() throws Exception {
        priceCalculationService = mock(PriceCalculationService.class);
        HealthStatusManager health = new HealthStatusManager();
        health.setStatus(HealthStatusManager.SERVICE_NAME_ALL_SERVICES, HealthCheckResponse.ServingStatus.SERVING);

        String name = InProcessServerBuilder.generateName();
        server = InProcessServerBuilder.forName(name)
                .directExecutor()
                .addService(new PricingGrpcService(priceCalculationService))
                .addService(health.getHealthService())
                .build()
                .start();
        channel = InProcessChannelBuilder.forName(name).directExecutor().build();
    }

    @AfterEach
    void stopInProcessServer() throws Exception {
        channel.shutdownNow().awaitTermination(5, TimeUnit.SECONDS);
        server.shutdownNow().awaitTermination(5, TimeUnit.SECONDS);
    }

    @Test
    @DisplayName("CalculatePrice request and response survive serialization over the wire")
    void calculatePriceRoundTrip() {
        Money basePrice = Money.usd(BigDecimal.valueOf(500.00));
        Money discount = Money.usd(BigDecimal.valueOf(50.00));
        when(priceCalculationService.calculateBasePrice("PROD-1", 5, "USD")).thenReturn(basePrice);
        when(priceCalculationService.calculateDiscount(eq("PROD-1"), eq(basePrice), anyString(), anyMap()))
                .thenReturn(discount);
        when(priceCalculationService.requiresApproval(any(), any())).thenReturn(false);

        PriceResponse response = PricingServiceGrpc.newBlockingStub(channel)
                .calculatePrice(PriceRequest.newBuilder()
                        .setProductId("PROD-1")
                        .setQuantity(5)
                        .setCurrencyCode("USD")
                        .setCustomerId("CUST-1")
                        .putAllConfiguration(Map.of("color", "red"))
                        .build());

        assertEquals("500.00", response.getPriceAmount());
        assertEquals("USD", response.getCurrencyCode());
        assertEquals("50.00", response.getDiscountAmount());
        assertEquals("450.00", response.getFinalAmount());
        assertFalse(response.getApprovalRequired());
    }

    @Test
    @DisplayName("grpc-services health check (pre-generated protobuf classes) answers SERVING")
    void healthCheckFromGrpcServices() {
        HealthCheckResponse response = HealthGrpc.newBlockingStub(channel)
                .check(HealthCheckRequest.newBuilder().setService("").build());

        assertEquals(HealthCheckResponse.ServingStatus.SERVING, response.getStatus());
    }
}
